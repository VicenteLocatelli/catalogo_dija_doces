function normalize(text) {
  return String(text || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}

function escapeHtml(text) {
  return String(text ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function formatPrice(value) {
  return typeof value === "number"
    ? value.toLocaleString("pt-BR", { style: "currency", currency: "BRL" })
    : "Consulte o preço";
}

function saveCart() {
  localStorage.setItem("irmaosMartinsCart", JSON.stringify(state.cart));
}

function cartQuantity(productId) {
  const item = state.cart.find(i => i.productId === productId);
  return item ? item.quantity : 0;
}

function totalCartItems() {
  return state.cart.reduce((sum, item) => sum + item.quantity, 0);
}

function getProduct(id) {
  return products.find(p => p.id === id);
}

function addToCart(id) {
  const product = getProduct(id);
  if (!product) return;
  const item = state.cart.find(i => i.productId === id);
  if (item) item.quantity += 1;
  else state.cart.push({ productId: id, quantity: 1 });
  saveCart();
  renderCart();
  renderProducts();
  showToast(`${product.family} adicionado ao pedido`);
}

function changeQuantity(id, delta) {
  const item = state.cart.find(i => i.productId === id);
  if (!item) return;
  item.quantity += delta;
  if (item.quantity <= 0) {
    state.cart = state.cart.filter(i => i.productId !== id);
  }
  saveCart();
  renderCart();
  renderProducts();
}

function removeFromCart(id) {
  state.cart = state.cart.filter(i => i.productId !== id);
  saveCart();
  renderCart();
  renderProducts();
}

function filteredProducts() {
  const q = normalize(state.search);
  let list = products.filter(p => {
    const categoryOk = state.category === "Todos" || p.category === state.category;
    const brandOk = !state.brand || p.brand === state.brand;
    const text = normalize([p.brand, p.name, p.family, p.variation, p.category].join(" "));
    return categoryOk && brandOk && (!q || text.includes(q));
  });
  return list;
}

